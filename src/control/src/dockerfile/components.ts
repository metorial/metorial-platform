import type { BuildMigration, BuildSpec, RenderContext } from './types';

export let bunVersion = '1.4.2';
export let prismaVersion = '7.10.1';
export let nodeImage = 'node:22.22.0-bookworm-slim';
export let user = { name: 'metorial', id: 10001 };

let turboSecrets =
  '--mount=type=secret,id=turbo_token,required=false --mount=type=secret,id=turbo_signature,required=false';
let bunCache = '--mount=type=cache,target=/root/.bun/install/cache';

export let join = (blocks: string[][]) =>
  blocks.map(block => block.join('\n')).join('\n\n') + '\n';

export let header = (): string[] => [
  '# syntax=docker/dockerfile:1.7',
  '# Generated by `control docker generate` from the build spec in control/index.ts.',
  '# Do not edit by hand: changes are overwritten on the next generation.'
];

export let base = (context: RenderContext): string[] => {
  let packages = [
    ...new Set([
      'ca-certificates',
      'python3',
      'python3-setuptools',
      'make',
      'g++',
      ...context.build.packages.build
    ])
  ];

  return [
    `FROM oven/bun:${bunVersion} AS base`,
    'WORKDIR /app',
    `RUN apt-get update && apt-get install -y --no-install-recommends ${packages.join(' ')} && rm -rf /var/lib/apt/lists/*`
  ];
};

let filterName = (context: RenderContext) =>
  context.build.closure ? `${context.packageName}...` : context.packageName;

let filters = (context: RenderContext) =>
  [filterName(context), ...context.build.include].map(name => `--filter=${name}`).join(' ');

export let pruner = (context: RenderContext): string[] => [
  'FROM base AS pruner',
  'COPY . .',
  `RUN bun ./${context.tooling}/docker-build/prune.ts ${context.build.tasks.join(' ')} ${filters(context)}`,
  '',
  'FROM scratch AS pruned',
  'COPY --from=pruner /app/out/ /'
];

export let dependencies = (context: RenderContext): string[] => [
  'FROM base AS dependencies',
  ...(context.build.node
    ? [`COPY --from=${nodeImage} /usr/local/bin/node /usr/local/bin/node`]
    : []),
  'COPY --from=pruned /json/ ./',
  `RUN ${bunCache} bun install --linker=hoisted`
];

let turboRuns = (context: RenderContext) => {
  let { build } = context;
  if (!build.include.length)
    return [`${build.tasks.join(' ')} --filter=${filterName(context)}`];

  let generate = build.tasks.filter(task => task === 'prisma:generate');
  let rest = build.tasks.filter(task => task !== 'prisma:generate');

  return [
    ...(generate.length ? [`${generate.join(' ')} ${filters(context)}`] : []),
    ...(rest.length ? [`${rest.join(' ')} --filter=${filterName(context)}`] : [])
  ];
};

let stripModules = (names: string[]) =>
  names.length
    ? [
        `RUN find /app/node_modules -type d \\( ${names.map(name => `-path '*/node_modules/${name}'`).join(' -o ')} \\) -prune -exec rm -rf {} +`
      ]
    : [];

export let builder = (context: RenderContext): string[] => {
  let { build, packageDirectory } = context;
  let concurrency = build.concurrency ? ` --concurrency=${build.concurrency}` : '';

  return [
    'FROM dependencies AS builder',
    'ARG TURBO_API',
    'ARG TURBO_TEAM',
    'ENV TURBO_API=${TURBO_API}',
    'ENV TURBO_TEAM=${TURBO_TEAM}',
    ...(build.heapMb ? [`ENV NODE_OPTIONS=--max_old_space_size=${build.heapMb}`] : []),
    ...Object.entries(build.buildEnv).map(([key, value]) => `ENV ${key}=${value}`),
    'COPY --from=pruned /full/ ./',
    ...build.sources.map(source => `COPY ${source} ./${source}`),
    ...turboRuns(context).map(
      run =>
        `RUN ${turboSecrets} sh ./${context.tooling}/warp-cache/run-turbo.sh ${run}${concurrency}`
    ),
    ...stripModules(build.strip),
    ...(build.sentry
      ? [
          `RUN --mount=type=secret,id=sentry_auth_token,required=false sh -c 'if [ -s /run/secrets/sentry_auth_token ]; then export SENTRY_AUTH_TOKEN="$(cat /run/secrets/sentry_auth_token)"; fi; bun run --cwd ${packageDirectory} sentry:sourcemaps || true'`
        ]
      : [])
  ];
};

export let productionDependencies = (context: RenderContext): string[] => [
  'FROM base AS production-dependencies',
  ...(context.build.node
    ? [`COPY --from=${nodeImage} /usr/local/bin/node /usr/local/bin/node`]
    : []),
  'COPY --from=pruned /json/ ./',
  `RUN ${bunCache} bun install --linker=hoisted --production`,
  ...stripModules(context.build.strip)
];

export let controlRuntime = (context: RenderContext): string[] => [
  'FROM base AS control-runtime',
  'WORKDIR /runtime',
  `COPY ${context.runtime}/package.json ${context.runtime}/bun.lock ./`,
  `RUN ${bunCache} bun install --frozen-lockfile`,
  `COPY ${context.runtime}/src ./src`,
  'RUN bun build ./src/cli.ts --target=bun --outfile=./control-runtime.js'
];

export let prismaCli = (): string[] => [
  'FROM base AS prisma-cli',
  'WORKDIR /opt/prisma',
  `RUN ${bunCache} bun add prisma@${prismaVersion} && ./node_modules/.bin/prisma --version`
];

let runtimeConfig = (context: RenderContext) => {
  let databases = context.build.migrations.map(
    ({ package: _package, path: _path, ...migration }: BuildMigration) => ({
      ...migration,
      schema: context.schemas[migration.name]!.target
    })
  );

  return JSON.stringify({ databases }, null, 2).split('\n');
};

export let runnerBase = (context: RenderContext): string[] => {
  let runtimePackages = [
    ...new Set(['ca-certificates', 'curl', 'tini', ...context.build.packages.runtime])
  ];

  return [
    `FROM oven/bun:${bunVersion}-slim AS runner-base`,
    `RUN apt-get update && apt-get install -y --no-install-recommends ${runtimePackages.join(' ')} && rm -rf /var/lib/apt/lists/* \\`,
    ` && groupadd --system --gid ${user.id} ${user.name} \\`,
    ` && useradd --system --uid ${user.id} --gid ${user.name} --create-home --shell /usr/sbin/nologin ${user.name}`,
    'WORKDIR /app'
  ];
};

export let tools = (): string[] => {
  let owner = `--chown=${user.id}:${user.id}`;

  return [
    'FROM runner-base AS tools',
    `COPY --from=control-runtime --link ${owner} /runtime/control-runtime.js ./control/control-runtime.js`,
    `COPY --from=prisma-cli --link ${owner} /opt/prisma /opt/prisma`
  ];
};

let releaseLines = (build: BuildSpec) => [
  ...(build.release
    ? [
        'ARG METORIAL_RELEASE_CHANNEL=dev',
        'ENV METORIAL_RELEASE_CHANNEL=${METORIAL_RELEASE_CHANNEL}'
      ]
    : []),
  ...(build.versioned
    ? ['ARG METORIAL_BUILD_VERSION', 'ENV METORIAL_VERSION=${METORIAL_BUILD_VERSION}']
    : [])
];

let sourceRunner = (context: RenderContext): string[] => {
  let { build, packageDirectory } = context;

  return [
    'FROM builder AS runner',
    'ENV NODE_ENV=production',
    'ENV TZ=UTC',
    ...Object.entries(build.env).map(([key, value]) => `ENV ${key}=${value}`),
    ...releaseLines(build),
    `WORKDIR /app/${packageDirectory}`,
    `CMD ${JSON.stringify(['bun', `./${build.start}`])}`
  ];
};

export let runner = (context: RenderContext): string[] => {
  let { build, packageDirectory } = context;
  if (build.runtime === 'source') return sourceRunner(context);

  let owner = `--chown=${user.id}:${user.id}`;
  let migrating = build.migrations.length > 0;

  let lines = [
    `FROM ${migrating ? 'tools' : 'runner-base'} AS runner`,
    'ENV NODE_ENV=production',
    'ENV TZ=UTC',
    ...Object.entries(build.env).map(([key, value]) => `ENV ${key}=${value}`),
    ...releaseLines(build)
  ];

  if (build.modules === 'production')
    lines.push(
      `COPY --from=production-dependencies --link ${owner} /app/node_modules ./node_modules`
    );

  lines.push(
    `COPY --from=builder --link ${owner} /app/${packageDirectory}/dist ./dist`,
    ...build.assets.map(
      asset =>
        `COPY --from=builder --link ${owner} /app/${asset.from.startsWith('/') ? asset.from.slice(1) : `${packageDirectory}/${asset.from}`} ./${asset.to}`
    )
  );

  if (migrating) {
    lines.push(
      ...build.migrations.map(migration => {
        let { source, target, directory } = context.schemas[migration.name]!;
        let slash = directory ? '/' : '';

        return `COPY --from=builder --link ${owner} /app/${source}${slash} ./${target}${slash}`;
      }),
      `COPY --link ${owner} <<'EOF' ./.control/runtime.json`,
      ...runtimeConfig(context),
      'EOF',
      'ENV PRISMA_BIN=/opt/prisma/node_modules/.bin/prisma'
    );
  }

  lines.push(`USER ${user.name}`);

  if (build.ports.length) lines.push(`EXPOSE ${build.ports.join(' ')}`);

  if (build.health.length)
    lines.push(
      'HEALTHCHECK --interval=30s --timeout=5s --start-period=40s --retries=3 \\',
      `  CMD ${build.health.map(check => `curl -fsS http://127.0.0.1:${check.port}${check.path}`).join(' && ')} || exit 1`
    );

  let start = `bun ./${build.start}`;
  lines.push(
    'ENTRYPOINT ["/usr/bin/tini", "--"]',
    migrating
      ? `CMD ["sh", "-c", "bun ./control/control-runtime.js migrate ${build.migrations.map(m => m.name).join(' ')} && exec ${start}"]`
      : `CMD ${JSON.stringify(start.split(' '))}`
  );

  return lines;
};
