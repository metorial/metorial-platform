use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

use crate::error::{BackendError, BackendResult};
use crate::multipart::{GIB, MIB};

/// Durable uploads follow the strictest rules across providers, so a caller never depends on one
/// backend's leniency: every part but the last is at least this large.
pub const DURABLE_MIN_PART_SIZE: u64 = 5 * MIB;

pub const DURABLE_MAX_PART_SIZE: u64 = 5 * GIB;

pub const DURABLE_MAX_PARTS: u32 = 10_000;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DurablePart {
    pub number: u32,
    pub size: u64,
    pub etag: String,
}

/// A part as named in a completion request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DurablePartRef {
    pub number: u32,
    pub etag: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DurableUpload {
    pub key: String,
    pub upload_id: String,
    pub initiated: Option<DateTime<Utc>>,
}

pub fn unsupported(backend: &str) -> BackendError {
    BackendError::Unsupported(format!(
        "the {} backend does not support durable multipart uploads",
        backend
    ))
}

pub fn validate_part_number(number: u32) -> BackendResult<()> {
    if number == 0 || number > DURABLE_MAX_PARTS {
        return Err(BackendError::InvalidRequest(format!(
            "part numbers run from 1 to {}, got {}",
            DURABLE_MAX_PARTS, number
        )));
    }
    Ok(())
}

pub fn validate_part_size(size: u64) -> BackendResult<()> {
    if size == 0 {
        return Err(BackendError::InvalidRequest("a part cannot be empty".to_string()));
    }
    if size > DURABLE_MAX_PART_SIZE {
        return Err(BackendError::TooLarge(format!(
            "a part holds at most {} bytes, got {}",
            DURABLE_MAX_PART_SIZE, size
        )));
    }
    Ok(())
}

/// Parts must be numbered 1..=n without gaps or repeats, in order.
pub fn validate_part_list(parts: &[DurablePartRef]) -> BackendResult<()> {
    if parts.is_empty() {
        return Err(BackendError::InvalidRequest(
            "a completed upload needs at least one part".to_string(),
        ));
    }
    if parts.len() > DURABLE_MAX_PARTS as usize {
        return Err(BackendError::InvalidRequest(format!(
            "an upload has at most {} parts",
            DURABLE_MAX_PARTS
        )));
    }

    for (index, part) in parts.iter().enumerate() {
        let expected = index as u32 + 1;
        if part.number != expected {
            return Err(BackendError::InvalidRequest(format!(
                "parts must be numbered 1 to {} in order; position {} holds part {}",
                parts.len(),
                expected,
                part.number
            )));
        }
    }
    Ok(())
}

/// Checks the sizes of the parts being completed, in order: all but the last meet the minimum.
pub fn validate_part_sizes(sizes: &[u64]) -> BackendResult<()> {
    let Some((_, leading)) = sizes.split_last() else {
        return Ok(());
    };

    for (index, size) in leading.iter().enumerate() {
        if *size < DURABLE_MIN_PART_SIZE {
            return Err(BackendError::InvalidRequest(format!(
                "part {} holds {} bytes; every part but the last needs at least {}",
                index + 1,
                size,
                DURABLE_MIN_PART_SIZE
            )));
        }
    }
    Ok(())
}

/// Upload ids are generated by us or a provider and travel in paths and queries, so only a
/// conservative alphabet is accepted.
pub fn validate_upload_id(upload_id: &str) -> BackendResult<()> {
    let valid = !upload_id.is_empty()
        && upload_id.len() <= 1024
        && upload_id
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || b"-_.~=+/".contains(&byte));

    if !valid {
        return Err(BackendError::InvalidRequest("invalid upload id".to_string()));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn refs(numbers: &[u32]) -> Vec<DurablePartRef> {
        numbers
            .iter()
            .map(|number| DurablePartRef {
                number: *number,
                etag: format!("e{}", number),
            })
            .collect()
    }

    #[test]
    fn accepts_contiguous_part_lists() {
        assert!(validate_part_list(&refs(&[1])).is_ok());
        assert!(validate_part_list(&refs(&[1, 2, 3])).is_ok());
    }

    #[test]
    fn rejects_gaps_repeats_and_empty_lists() {
        for numbers in [&[][..], &[2], &[1, 3], &[1, 1], &[2, 1]] {
            assert!(
                matches!(
                    validate_part_list(&refs(numbers)),
                    Err(BackendError::InvalidRequest(_))
                ),
                "{numbers:?}"
            );
        }
    }

    #[test]
    fn only_the_last_part_may_be_small() {
        assert!(validate_part_sizes(&[1]).is_ok());
        assert!(validate_part_sizes(&[DURABLE_MIN_PART_SIZE, 1]).is_ok());
        assert!(validate_part_sizes(&[DURABLE_MIN_PART_SIZE - 1, DURABLE_MIN_PART_SIZE]).is_err());
    }

    #[test]
    fn bounds_part_numbers_and_sizes() {
        assert!(validate_part_number(0).is_err());
        assert!(validate_part_number(1).is_ok());
        assert!(validate_part_number(DURABLE_MAX_PARTS).is_ok());
        assert!(validate_part_number(DURABLE_MAX_PARTS + 1).is_err());
        assert!(validate_part_size(0).is_err());
        assert!(validate_part_size(DURABLE_MAX_PART_SIZE + 1).is_err());
    }

    #[test]
    fn accepts_only_safe_upload_ids() {
        assert!(validate_upload_id("2~abc_DEF-123.x=").is_ok());
        assert!(validate_upload_id("").is_err());
        assert!(validate_upload_id("a b").is_err());
        assert!(validate_upload_id("a\nb").is_err());
        assert!(validate_upload_id("..%2f").is_err());
    }
}
