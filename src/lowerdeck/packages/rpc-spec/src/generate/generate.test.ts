import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { describe, expect, test } from 'vitest';
import { compile } from '../compile';
import bucket from '../fixtures/bucket';
import { error, method, service } from '../spec';
import * as t from '../builders';
import { generateGo } from './go';
import { generateTs } from './ts';

let goldenGo = new URL(
  '../../../../go/ldrpc/example/bucketrpc/bucketrpc.gen.go',
  import.meta.url
);
let goldenTs = new URL('../../../../go/ldrpc/interop/generated/bucket.ts', import.meta.url);
let hasGofmt = spawnSync('gofmt', ['-h']).error === undefined;

let gofmt = (source: string) => {
  let result = spawnSync('gofmt', [], { input: source, encoding: 'utf8' });
  if (result.status !== 0) throw new Error(result.stderr);
  return result.stdout;
};

let kitchenSink = service({
  name: 'kitchen-sink',
  description: 'Every type kind.\n\nSecond paragraph.',
  go: { package: 'sinkrpc' },
  ts: { client: 'SinkClient' },
  methods: {
    everything: method({
      input: t.object({
        text: t.string({ minLength: 1, format: 'url' }),
        flag: t.boolean(),
        count: t.int({ min: 0 }),
        ratio: t.number(),
        at: t.datetime(),
        blob: t.bytes(),
        raw: t.json(),
        on: t.literal(true),
        level: t.literal(2),
        tags: t.array(t.string()).optional(),
        maybeTags: t.array(t.string()).nullable(),
        nested: t.array(t.array(t.int().nullable())),
        labels: t.record(t.datetime()),
        alias: t.string({ maxLength: 3 }).named('ShortCode'),
        aliasList: t.array(t.string()).named('NameList'),
        when: t.datetime().named('Timestamp').optional(),
        deprecatedField: t.string().optional().deprecated('use text'),
        shape: t.union('kind', {
          circle: t.object({ radius: t.number() }),
          square: t.object({ side: t.number(), at: t.datetime().nullable() })
        }),
        optionalShape: t
          .union('kind', { dot: t.object({}) })
          .named('MaybeShape')
          .nullable()
      }),
      output: t.void(),
      errors: [
        error({
          status: 409,
          code: 'too_late',
          message: 'Too late.',
          description: 'The deadline passed.',
          data: { reason: t.string(), at: t.datetime(), retryAfter: t.int().optional() }
        })
      ]
    })
      .idempotent(false)
      .deprecated('use everythingV2')
  }
});

describe('generateGo', () => {
  test('bucket fixture matches example/bucketrpc', () => {
    expect(generateGo(compile(bucket))).toBe(readFileSync(goldenGo, 'utf8'));
  });

  test.skipIf(!hasGofmt)('output is gofmt-clean', () => {
    for (let spec of [bucket, kitchenSink]) {
      let source = generateGo(compile(spec));
      expect(gofmt(source)).toBe(source);
    }
  });

  test('maps every type kind', () => {
    let source = generateGo(compile(kitchenSink));

    expect(source).toContain(
      '// Code generated by @lowerdeck/rpc-spec from the kitchen-sink spec. DO NOT EDIT.'
    );
    expect(source).toMatch(/Text +string +`json:"text"`/);
    expect(source).toMatch(/Count +int64 +`json:"count"`/);
    expect(source).toMatch(/Ratio +float64 +`json:"ratio"`/);
    expect(source).toMatch(/At +time\.Time +`json:"at"`/);
    expect(source).toMatch(/Blob +\[\]byte +`json:"blob" ldrpc:"nonnil"`/);
    expect(source).toMatch(/Raw +json\.RawMessage +`json:"raw"`/);
    expect(source).toMatch(/On +bool +`json:"on"`/);
    expect(source).toMatch(/Level +float64 +`json:"level"`/);
    expect(source).toMatch(/Tags +\[\]string +`json:"tags,omitempty"`/);
    expect(source).toMatch(/MaybeTags +\[\]string +`json:"maybeTags"`/);
    expect(source).toMatch(/Nested +\[\]\[\]\*int64 +`json:"nested" ldrpc:"nonnil"`/);
    expect(source).toMatch(/Labels +map\[string\]time\.Time +`json:"labels" ldrpc:"nonnil"`/);
    expect(source).toMatch(/AliasList +NameList +`json:"aliasList" ldrpc:"nonnil"`/);
    expect(source).toMatch(/When +\*Timestamp +`json:"when,omitempty"`/);
    expect(source).toMatch(/OptionalShape +\*MaybeShape +`json:"optionalShape"`/);
    expect(source).toContain('// Deprecated: use text\n\tDeprecatedField *string');
    expect(source).toContain('type ShortCode string');
    expect(source).toContain('type NameList []string');
    expect(source).toContain('type Timestamp = time.Time');
    expect(source).toContain(
      'type EverythingInputShapeVariant interface {\n\tisEverythingInputShape()\n}'
    );
    expect(source).toContain('type MaybeShapeDot struct{}');
    expect(source).toContain(
      'func ErrTooLate(reason string, at time.Time, retryAfter *int64) *ldrpc.Error {\n\terr := ldrpc.NewError(409, CodeTooLate, "Too late.").WithReason(reason).With("at", at)\n\tif retryAfter != nil {\n\t\terr = err.With("retryAfter", *retryAfter)\n\t}\n\treturn err\n}'
    );
    expect(source).toContain(
      '// Deprecated: use everythingV2\n\tEverything(ctx context.Context, in *EverythingInput) (*ldrpc.Void, error)'
    );
    expect(source).toContain('append([]ldrpc.CallOption{ldrpc.WithoutRetry()}, opts...)...');
  });

  test('embeds the IR of every type reachable from an input as its schema', () => {
    let source = generateGo(compile(kitchenSink));
    let literal = source.match(/MustParseSchemas\(`([\s\S]*?)`\)/)![1]!;
    let schemas = JSON.parse(literal);

    expect(Object.keys(schemas).sort()).toEqual(
      [
        'EverythingInput',
        'EverythingInputShape',
        'EverythingInputShapeCircle',
        'EverythingInputShapeSquare',
        'MaybeShape',
        'MaybeShapeDot',
        'NameList',
        'ShortCode',
        'Timestamp'
      ].sort()
    );
    expect(schemas.ShortCode).toEqual({
      kind: 'alias',
      type: { kind: 'string', maxLength: 3 }
    });
    expect(JSON.stringify(schemas)).not.toContain('use text');
  });

  test('rejects identifiers that would collide', () => {
    let spec = service({
      name: 'clash',
      go: { package: 'clashrpc' },
      ts: { client: 'ClashClient' },
      methods: {
        get: method({
          input: t.object({ status: t.enum(['a']).named('Status') }),
          output: t.object({ other: t.string().named('StatusA') })
        })
      }
    });

    expect(() => generateGo(compile(spec))).toThrow(/StatusA is used by both/);
  });
});

describe('generateTs', () => {
  test('bucket fixture matches interop/generated/bucket.ts', () => {
    expect(
      generateTs(compile(bucket), {
        clientImport: '../../../../packages/rpc-client/src/index.ts'
      })
    ).toBe(readFileSync(goldenTs, 'utf8'));
  });

  test('non-idempotent methods are registered with the client', () => {
    let source = generateTs(compile(kitchenSink));

    expect(source).toContain('export let sinkNonIdempotentMethods = ["everything"] as const;');
    expect(source).toContain(
      'nonIdempotentMethods: [...(opts.nonIdempotentMethods ?? []), ...sinkNonIdempotentMethods]'
    );
    expect(source).toContain('Not idempotent: the client never retries it.');
  });
});
