import type { IR, IRField, IRMethod, IRNamedType, IRType } from '../ir';
import { camelCase } from '../names';

export type TsGeneratorOptions = {
  clientImport?: string;
};

let identifierPattern = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

let docComment = (indent: string, text?: string, deprecated?: string) => {
  let lines = text ? text.split('\n') : [];
  if (deprecated !== undefined) lines.push(deprecated ? `@deprecated ${deprecated}` : '@deprecated');
  if (!lines.length) return '';

  if (lines.length == 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map(line => `${indent} * ${line}`).join('\n')}\n${indent} */\n`;
};

let propertyKey = (name: string) => (identifierPattern.test(name) ? name : JSON.stringify(name));

let needsParens = (type: IRType) => type.kind == 'nullable';

export let tsType = (type: IRType): string => {
  switch (type.kind) {
    case 'ref':
      return type.name;
    case 'nullable':
      return `${tsType(type.type)} | null`;
    case 'string':
    case 'bytes':
      return 'string';
    case 'int':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'datetime':
      return 'Date';
    case 'json':
      return 'unknown';
    case 'void':
      return 'void';
    case 'literal':
      return JSON.stringify(type.value);
    case 'array': {
      let items = tsType(type.items);
      return needsParens(type.items) ? `(${items})[]` : `${items}[]`;
    }
    case 'record':
      return `Record<string, ${tsType(type.values)}>`;
  }
};

let objectBody = (fields: IRField[], indent: string, prefix: string[] = []) => {
  let lines = [
    ...prefix.map(line => `${indent}${line}`),
    ...fields.map(
      field =>
        `${docComment(indent, field.description, field.deprecated)}${indent}${propertyKey(field.name)}${field.optional ? '?' : ''}: ${tsType(field.type)};`
    )
  ];

  return lines.length ? `{\n${lines.join('\n')}\n${indent.slice(2)}}` : '{}';
};

let namedType = (ir: IR, type: IRNamedType) => {
  let doc = docComment('', type.description, type.deprecated);

  switch (type.kind) {
    case 'object':
      return `${doc}export type ${type.name} = ${objectBody(type.fields, '  ')};`;

    case 'enum':
      return `${doc}export type ${type.name} = ${type.values.map(value => JSON.stringify(value)).join(' | ')};`;

    case 'alias':
      return `${doc}export type ${type.name} = ${tsType(type.type)};`;

    case 'union': {
      let variants = type.variants.map(
        variant =>
          `\n  | ({ ${propertyKey(type.discriminator)}: ${JSON.stringify(variant.tag)} } & ${variant.type})`
      );
      return `${doc}export type ${type.name} =${variants.join('')};`;
    }
  }
};

type Tree = { [key: string]: Tree | IRMethod };

let clientTree = (methods: IRMethod[]) => {
  let root: Tree = {};
  for (let method of methods) {
    let node = root;
    for (let segment of method.path.slice(0, -1)) node = (node[segment] ??= {}) as Tree;
    node[method.path[method.path.length - 1]!] = method;
  }
  return root;
};

let renderTree = (tree: Tree, indent: string): string => {
  let entries = Object.entries(tree).map(([key, value]) => {
    if ('path' in value && Array.isArray(value.path)) {
      let method = value as IRMethod;
      return `${docComment(indent, method.description, method.deprecated)}${indent}${key}: RpcMethod<${tsType(method.input)}, ${tsType(method.output)}>;`;
    }
    return `${indent}${key}: ${renderTree(value as Tree, `${indent}  `)};`;
  });

  return `{\n${entries.join('\n')}\n${indent.slice(2)}}`;
};

export let generateTs = (ir: IR, opts: TsGeneratorOptions = {}) => {
  let client = ir.service.ts.client;
  let base = client.replace(/Client$/, '') || client;
  let lower = camelCase(base);
  let errors = Object.values(ir.errors);

  let sections = [
    `// Code generated by @lowerdeck/rpc-spec from the ${ir.service.name} spec. DO NOT EDIT.\n\nimport { createClient, type ClientOpts, type RpcMethod } from '${opts.clientImport ?? '@lowerdeck/rpc-client'}';`,
    ...Object.values(ir.types).map(type => namedType(ir, type)),
    `${docComment('', ir.service.description)}export type ${client} = ${renderTree(clientTree(ir.methods), '  ')};`,
    `export let ${lower}ErrorCodes = [${errors.map(error => JSON.stringify(error.code)).join(', ')}] as const;`,
    `export type ${base}ErrorCode = (typeof ${lower}ErrorCodes)[number];`,
    `export type ${base}ErrorData = ${
      errors.length
        ? `{\n${errors.map(error => `  ${error.code}: ${objectBody(error.data, '    ')};`).join('\n')}\n}`
        : 'Record<never, never>'
    };`,
    `export let create${client} = (opts: ClientOpts) => createClient<${client}>(opts);`
  ];

  return `${sections.join('\n\n')}\n`;
};
