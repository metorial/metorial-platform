import { beforeEach, describe, expect, it, vi } from 'vitest';

let { db, fileService, serializer, replaceRows, log } = vi.hoisted(() => ({
  db: {
    skillDestinationItem: {
      findFirst: vi.fn(),
      update: vi.fn(),
      create: vi.fn(),
      deleteMany: vi.fn()
    },
    skillDestinationFile: { deleteMany: vi.fn() },
    skillMarketplace: { findUnique: vi.fn() },
    skillPlugin: { findUnique: vi.fn() },
    skillMarketplacePlugin: { findFirst: vi.fn() },
    file: { findMany: vi.fn() }
  },
  fileService: { getContentHashes: vi.fn(), requestContentHashes: vi.fn() },
  serializer: {
    init: vi.fn(async () => ({})),
    getHash: vi.fn(async () => 'new-hash'),
    apply: vi.fn()
  },
  replaceRows: vi.fn(),
  log: vi.fn()
}));

vi.mock('@metorial/db', () => ({
  db,
  withTransaction: async (run: (tx: typeof db) => unknown) => run(db)
}));
vi.mock('@metorial/module-file', () => ({
  fileService,
  hasValidContentHashes: (file: { contentSha256: string | null }) => !!file.contentSha256,
  getCargoFilesBucketName: () => 'files',
  getStorage: () => ({
    putObject: vi.fn(),
    headObject: vi.fn(async () => ({}))
  })
}));
vi.mock('../../../env', () => ({
  env: { skillSync: { SKILL_SYNC_INLINE_HASH_MAX_BYTES: 64 * 1024 * 1024 } }
}));
vi.mock('../../../lib/limits', () => ({
  CargoSkillLimitError: class CargoSkillLimitError extends Error {}
}));
vi.mock('../../../serializers/marketplace', () => ({ applyMarketplace: serializer }));
vi.mock('../../../serializers/plugin', () => ({ applyPlugin: serializer }));
vi.mock('../../../serializers/skill', () => ({ applySkill: serializer }));
vi.mock('./manifestRows', () => ({ replaceSkillDestinationItemRows: replaceRows }));
vi.mock('./logs', () => ({ appendSkillDestinationSyncLog: log }));
vi.mock('./blobStore', () => ({
  putSkillSyncBlobs: async (d: { blobs: { bytes: Uint8Array }[]; reference: any }) => {
    let refs = d.blobs.map((_, i) => ({
      key: `skill-sync/blobs/sha256/${i}`,
      sha256: `${i}`.repeat(64),
      gitBlobSha: `${i}`.repeat(40),
      crc32: i,
      byteSize: 1
    }));
    return {
      blobs: refs,
      result: await d.reference(refs),
      written: refs.length,
      rewritten: 0
    };
  }
}));

import type { SerializerContext } from '../../../serializers/_lib/types';
import { processManifestSyncTask, type ManifestSyncDestination } from './manifestTask';

let mib = 1024 * 1024;

let destination = {
  oid: 1n,
  id: 'sdst_1',
  skillMarketplace: { oid: 2n, id: 'mkt_1', instanceOid: 10n },
  skillPlugin: null
} as unknown as ManifestSyncDestination;

let storedFile = (oid: bigint, overrides: Record<string, unknown> = {}) => ({
  oid,
  id: `file_${oid}`,
  status: 'active',
  storeId: `files/${oid}`,
  fileSize: 3,
  contentSha256: 'f'.repeat(64),
  contentSha256StoreId: `files/${oid}`,
  contentGitBlobSha: 'f'.repeat(40),
  contentCrc32: 1n,
  ...overrides
});

let emit = (write: (context: SerializerContext) => Promise<void>) =>
  serializer.apply.mockImplementation(async (_input: unknown, context: SerializerContext) =>
    write(context)
  );

let runTask = (liveItemKeys = new Set<string>()) =>
  processManifestSyncTask({
    skillDestinationSyncId: 'sync_1',
    destination,
    task: { type: 'marketplace', action: 'set', skillMarketplaceId: 'mkt_1' },
    liveItemKeys
  });

describe('processManifestSyncTask', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    serializer.getHash.mockResolvedValue('new-hash');
    db.skillMarketplace.findUnique.mockResolvedValue({ oid: 2n, id: 'mkt_1', name: 'Market' });
    db.skillDestinationItem.findFirst.mockResolvedValue({ oid: 4n, hash: 'old-hash' });
    db.file.findMany.mockImplementation(async ({ where }: any) =>
      where.oid.in.map((oid: bigint) => ({ oid }))
    );
    fileService.getContentHashes.mockImplementation(async ({ file }: any) => ({
      sha256: file.contentSha256,
      gitBlobSha: file.contentGitBlobSha,
      crc32: 1,
      size: file.fileSize
    }));
    replaceRows.mockResolvedValue({
      created: 1,
      updated: 0,
      deleted: 0,
      unchanged: 0,
      conflicts: []
    });
  });

  it('skips an item whose hash is unchanged without rendering it', async () => {
    serializer.getHash.mockResolvedValue('old-hash');

    expect(await runTask()).toEqual({ type: 'skipped' });
    expect(serializer.apply).not.toHaveBeenCalled();
    expect(replaceRows).not.toHaveBeenCalled();
  });

  it('writes generated bytes as blobs and stored files by reference, then stores the hash', async () => {
    emit(async context => {
      await context.setFile('.claude-plugin/marketplace.json', '{}');
      await context.setFileFromStorage('plugins/p/skills/s/a.png', storedFile(7n) as any);
    });
    let liveItemKeys = new Set<string>();

    expect(await runTask(liveItemKeys)).toEqual({ type: 'changed' });

    expect(replaceRows).toHaveBeenCalledWith({
      destinationOid: 1n,
      itemKey: 'marketplace:mkt_1',
      liveItemKeys,
      rows: [
        {
          path: '.claude-plugin/marketplace.json',
          gitBlobSha: '0'.repeat(40),
          sha256: '0'.repeat(64),
          byteSize: 1n,
          crc32: 0n,
          sourceKind: 'blob',
          sourceKey: 'skill-sync/blobs/sha256/0',
          sourceFileOid: null
        },
        {
          path: 'plugins/p/skills/s/a.png',
          gitBlobSha: 'f'.repeat(40),
          sha256: 'f'.repeat(64),
          byteSize: 3n,
          crc32: 1n,
          sourceKind: 'file',
          sourceKey: 'files/7',
          sourceFileOid: 7n
        }
      ]
    });
    expect(db.skillDestinationItem.update).toHaveBeenCalledWith({
      where: { oid: 4n },
      data: { hash: 'new-hash' }
    });
    expect(liveItemKeys.has('marketplace:mkt_1')).toBe(true);
  });

  it('creates the item on first apply', async () => {
    db.skillDestinationItem.findFirst.mockResolvedValue(null);
    replaceRows.mockResolvedValue({
      created: 0,
      updated: 0,
      deleted: 0,
      unchanged: 0,
      conflicts: []
    });
    emit(async () => {});

    expect(await runTask()).toEqual({ type: 'changed' });
    expect(db.skillDestinationItem.create).toHaveBeenCalledWith({
      data: { destinationOid: 1n, skillMarketplaceOid: 2n, hash: 'new-hash' }
    });
  });

  it('drops invalid paths and logs them', async () => {
    emit(async context => {
      await context.setFile('ok.md', 'x');
      await context.setFile('bad/.git/hooks/pre-commit', 'x');
    });

    await runTask();

    expect(
      replaceRows.mock.calls[0]![0].rows.map((row: { path: string }) => row.path)
    ).toEqual(['ok.md']);
    expect(log).toHaveBeenCalledWith('sync_1', expect.stringContaining('invalid_path'));
  });

  it('rejects stored files from another instance', async () => {
    emit(async context => {
      await context.setFileFromStorage('mine.bin', storedFile(7n) as any);
      await context.setFileFromStorage('theirs.bin', storedFile(8n) as any);
    });
    db.file.findMany.mockResolvedValue([{ oid: 7n }]);

    await runTask();

    expect(db.file.findMany.mock.calls[0]![0].where.OR[0]).toEqual({ instanceOid: 10n });
    expect(
      replaceRows.mock.calls[0]![0].rows.map((row: { path: string }) => row.path)
    ).toEqual(['mine.bin']);
    expect(log).toHaveBeenCalledWith('sync_1', expect.stringContaining('cross_instance_file'));
  });

  it('defers the task and requests hashes for large files without them', async () => {
    let large = storedFile(9n, { fileSize: 65 * mib, contentSha256: null });
    emit(async context => {
      await context.setFileFromStorage('big.bin', large as any);
    });

    expect(await runTask()).toEqual({ type: 'deferred', fileCount: 1 });
    expect(fileService.requestContentHashes).toHaveBeenCalledWith({ file: large });
    expect(fileService.getContentHashes).not.toHaveBeenCalled();
    expect(replaceRows).not.toHaveBeenCalled();
    expect(db.skillDestinationItem.update).not.toHaveBeenCalled();
  });

  it('fails with a limit error for files over the per-file cap', async () => {
    emit(async context => {
      await context.setFileFromStorage(
        'huge.bin',
        storedFile(9n, { fileSize: 3 * 1024 * mib }) as any
      );
    });

    await expect(runTask()).rejects.toThrow(/huge\.bin.*cannot exceed/);
    expect(replaceRows).not.toHaveBeenCalled();
  });

  it('logs paths another item kept', async () => {
    emit(async context => {
      await context.setFile('shared.json', '{}');
    });
    replaceRows.mockResolvedValue({
      created: 0,
      updated: 0,
      deleted: 0,
      unchanged: 0,
      conflicts: [{ path: 'shared.json', ownerItemKey: 'marketplace:a' }]
    });

    expect(await runTask()).toEqual({ type: 'skipped' });
    expect(log).toHaveBeenCalledWith(
      'sync_1',
      expect.stringContaining('shared.json (marketplace:a)')
    );
  });

  it('deletes the rows and item of a removed plugin', async () => {
    db.skillPlugin.findUnique.mockResolvedValue({
      oid: 3n,
      id: 'plg_1',
      name: 'Plugin',
      skillPluginSkills: []
    });
    let liveItemKeys = new Set(['plugin:plg_1']);

    let outcome = await processManifestSyncTask({
      skillDestinationSyncId: 'sync_1',
      destination,
      task: { type: 'plugin', action: 'delete', skillPluginId: 'plg_1' },
      liveItemKeys
    });

    expect(outcome).toEqual({ type: 'changed' });
    expect(db.skillDestinationFile.deleteMany).toHaveBeenCalledWith({
      where: { destinationOid: 1n, itemKey: 'plugin:plg_1' }
    });
    expect(db.skillDestinationItem.deleteMany).toHaveBeenCalledWith({
      where: { destinationOid: 1n, skillPluginOid: 3n }
    });
    expect(liveItemKeys.size).toBe(0);
  });
});
