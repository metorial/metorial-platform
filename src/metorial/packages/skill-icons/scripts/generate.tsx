let toComponentName = (id: string) =>
  'Ri' +
  id
    .split('-')
    .map(part => part[0]!.toUpperCase() + part.slice(1))
    .join('');

let extractPaths = (markup: string) =>
  [...markup.matchAll(/ d="([^"]+)"/g)].map(match => match[1]!);

let entries = iconIds.map(id => {
  let component = (Remix as Record<string, any>)[toComponentName(id)];
  if (!component) throw new Error(`Unknown Remix icon: ${id}`);

  let paths = extractPaths(renderToStaticMarkup(createElement(component)));
  if (!paths.length) throw new Error(`No paths found for ${id}`);

  return [id, paths] as const;
});

let output = `// Generated by scripts/generate.tsx from @remixicon/react. Do not edit by hand.

export let SKILL_ICON_PATHS: Record<string, string[]> = {
${entries.map(([id, paths]) => `  '${id}': ${JSON.stringify(paths)}`).join(',\n')}
};
`;

writeFileSync(join(import.meta.dir, '../src/paths.ts'), output);

console.log(`Generated ${entries.length} skill icons`);
