import { eventually, expectServiceError, useOrganization } from '@metorial/e2e';
import { db, loadOrganizationFixture, type OrganizationFixture } from '@metorial/e2e/db';
import { createResourceAuthorization } from '@metorial/module-access';
import { describe, expect, it } from 'vitest';
import { skillForkSyncService, skillMergeRequestService } from '../src';
import {
  addDocument,
  createForkPair,
  createSkill,
  editDocument,
  ensureResourceActor,
  eventTypes,
  getItemByPath,
  getMergeRequest,
  listItems,
  mergeTimeout,
  privileged,
  readDocument,
  scopeOf,
  type SkillRecord,
  uniquePath
} from './_fixtures';

let startSync = async (
  fixture: OrganizationFixture,
  fork: SkillRecord,
  authorization = privileged
) =>
  await skillForkSyncService.createSkillForkSync({
    ...scopeOf(fixture),
    authorization,
    forkSkillId: fork.id
  });

let waitForSync = async (
  sync: { id: string },
  status: 'completed' | 'action_required' | 'cancelled' | 'failed'
) =>
  await eventually(async () => {
    let row = await db.skillForkSync.findUniqueOrThrow({
      where: { id: sync.id },
      include: { generatedMergeRequest: true }
    });
    expect(row.status).toBe(status);
    return row;
  }, mergeTimeout);

let generatedMergeRequest = async (
  fixture: OrganizationFixture,
  sync: { generatedMergeRequest: { id: string } | null }
) => {
  expect(sync.generatedMergeRequest).not.toBeNull();
  return await getMergeRequest(fixture, sync.generatedMergeRequest!.id);
};

describe('module-skill-merge-requests fork sync', () => {
  let org = useOrganization();
  let otherOrg = useOrganization();

  it('completes without a merge request when the upstream has not changed', async () => {
    let fixture = await loadOrganizationFixture(org.ids);
    let actor = await ensureResourceActor(fixture);
    let { upstream, fork } = await createForkPair(fixture);
    let forkPath = uniquePath('fork-only');
    await addDocument(fixture, fork, forkPath, 'fork work');

    let sync = await startSync(
      fixture,
      fork,
      createResourceAuthorization({ restricted: false, resourceActor: actor })
    );
    expect(sync).toMatchObject({
      status: 'pending',
      forkSkillOid: fork.oid,
      upstreamSkillOid: upstream.oid,
      createdByResourceActorOid: actor.oid,
      generatedMergeRequestOid: null
    });
    expect(sync.activePairKey).toEqual(expect.any(String));

    let completed = await waitForSync(sync, 'completed');
    expect(completed).toMatchObject({
      activePairKey: null,
      error: null,
      generatedMergeRequestOid: null
    });
    expect(completed.completedAt).toBeInstanceOf(Date);

    expect(await readDocument(fixture, fork, forkPath)).toBe('fork work');
    expect(
      await db.skillMergeRequest.count({
        where: { OR: [{ sourceSkillOid: fork.oid }, { targetSkillOid: fork.oid }] }
      })
    ).toBe(0);

    let fetched = await skillForkSyncService.getSkillForkSyncById({
      ...scopeOf(fixture),
      authorization: privileged,
      skillForkSyncId: sync.id
    });
    expect(fetched.status).toBe('completed');
  });

  it('pulls upstream changes into the fork through a merged sync request', async () => {
    let fixture = await loadOrganizationFixture(org.ids);
    let { upstream, fork } = await createForkPair(fixture);
    let upstreamPath = uniquePath('upstream-new');
    let forkPath = uniquePath('fork-own');
    await addDocument(fixture, upstream, upstreamPath, 'from upstream');
    await addDocument(fixture, fork, forkPath, 'fork work');

    let sync = await startSync(fixture, fork);
    let completed = await waitForSync(sync, 'completed');
    let mergeRequest = await generatedMergeRequest(fixture, completed);

    expect(mergeRequest).toMatchObject({
      direction: 'upstream_to_fork',
      status: 'merged',
      sourceSkillOid: upstream.oid,
      targetSkillOid: fork.oid,
      description: 'Generated by fork synchronization'
    });
    expect(mergeRequest.title).toContain('Sync');
    expect((await listItems(mergeRequest)).map(item => item.path)).toContain(upstreamPath);
    expect((await listItems(mergeRequest)).map(item => item.path)).not.toContain(forkPath);
    expect(await eventTypes(mergeRequest)).toEqual([
      'created',
      'merge_started',
      'merge_completed'
    ]);

    expect(await readDocument(fixture, fork, upstreamPath)).toBe('from upstream');
    expect(await readDocument(fixture, fork, forkPath)).toBe('fork work');
    expect(await readDocument(fixture, upstream, forkPath)).toBeUndefined();

    let again = await waitForSync(await startSync(fixture, fork), 'completed');
    expect(again.generatedMergeRequestOid).toBeNull();
  }, 180_000);

  it('waits for conflict resolution and completes once the sync request merges', async () => {
    let fixture = await loadOrganizationFixture(org.ids);
    let { upstream, fork } = await createForkPair(fixture);
    let path = uniquePath('contested');
    await addDocument(fixture, upstream, path, 'upstream version');
    await addDocument(fixture, fork, path, 'fork version');

    let sync = await startSync(fixture, fork);
    let waiting = await waitForSync(sync, 'action_required');
    expect(waiting.actionRequiredAt).toBeInstanceOf(Date);
    expect(waiting.activePairKey).toBe(sync.activePairKey);

    let mergeRequest = await generatedMergeRequest(fixture, waiting);
    expect(mergeRequest.status).toBe('open');
    let item = await getItemByPath(mergeRequest, path);
    expect(item).toMatchObject({ changeType: 'conflicted', status: 'unresolved' });

    let duplicate = await expectServiceError(startSync(fixture, fork), 'bad_request');
    expect(duplicate.message).toMatch(/active fork synchronization/);

    await expectServiceError(
      skillMergeRequestService.performSkillMergeRequest({
        ...scopeOf(fixture),
        authorization: privileged,
        mergeRequest
      }),
      'bad_request'
    );
    expect((await db.skillForkSync.findUniqueOrThrow({ where: { id: sync.id } })).status).toBe(
      'action_required'
    );

    await skillMergeRequestService.saveSkillMergeRequestItemResolution({
      ...scopeOf(fixture),
      authorization: privileged,
      mergeRequest,
      itemId: item.id,
      resolutionType: 'accept_source'
    });
    await skillMergeRequestService.performSkillMergeRequest({
      ...scopeOf(fixture),
      authorization: privileged,
      mergeRequest: await getMergeRequest(fixture, mergeRequest.id)
    });

    let completed = await waitForSync(sync, 'completed');
    expect(completed.activePairKey).toBeNull();
    expect(completed.generatedMergeRequest?.status).toBe('merged');
    expect(await readDocument(fixture, fork, path)).toBe('upstream version');
    expect(await readDocument(fixture, upstream, path)).toBe('upstream version');
  }, 180_000);

  it('cancels the sync when its merge request is closed and allows a fresh sync', async () => {
    let fixture = await loadOrganizationFixture(org.ids);
    let { upstream, fork } = await createForkPair(fixture);
    let path = uniquePath('contested');
    await addDocument(fixture, upstream, path, 'upstream version');
    await addDocument(fixture, fork, path, 'fork version');

    let sync = await startSync(fixture, fork);
    let waiting = await waitForSync(sync, 'action_required');
    let mergeRequest = await generatedMergeRequest(fixture, waiting);

    await skillMergeRequestService.closeSkillMergeRequest({
      ...scopeOf(fixture),
      auditScope: fixture.auditScope,
      authorization: privileged,
      mergeRequest
    });

    let cancelled = await db.skillForkSync.findUniqueOrThrow({ where: { id: sync.id } });
    expect(cancelled).toMatchObject({ status: 'cancelled', activePairKey: null });
    expect(cancelled.cancelledAt).toBeInstanceOf(Date);
    expect(await readDocument(fixture, fork, path)).toBe('fork version');

    await editDocument(fixture, fork, path, 'upstream version');

    let retried = await waitForSync(await startSync(fixture, fork), 'completed');
    expect(retried.id).not.toBe(sync.id);
    expect(retried.generatedMergeRequestOid).toBeNull();
    expect(await readDocument(fixture, fork, path)).toBe('upstream version');
    expect((await getMergeRequest(fixture, mergeRequest.id)).status).toBe('closed');
  }, 180_000);

  it('rejects syncs for skills that are not forks and isolates them per tenant', async () => {
    let fixture = await loadOrganizationFixture(org.ids);
    let other = await loadOrganizationFixture(otherOrg.ids);
    let standalone = await createSkill(fixture);
    let { fork } = await createForkPair(fixture);

    let notFork = await expectServiceError(startSync(fixture, standalone), 'bad_request');
    expect(notFork.message).toMatch(/must be a fork/);
    await expectServiceError(
      skillForkSyncService.createSkillForkSync({
        ...scopeOf(fixture),
        authorization: privileged,
        forkSkillId: 'skl_does_not_exist'
      }),
      'not_found'
    );
    await expectServiceError(startSync(other, fork), 'not_found');

    let sync = await startSync(fixture, fork);
    await expectServiceError(
      skillForkSyncService.getSkillForkSyncById({
        ...scopeOf(other),
        authorization: privileged,
        skillForkSyncId: sync.id
      }),
      'not_found'
    );
    await expectServiceError(
      skillForkSyncService.getSkillForkSyncById({
        ...scopeOf(fixture),
        authorization: privileged,
        skillForkSyncId: 'sksy_does_not_exist'
      }),
      'not_found'
    );

    await waitForSync(sync, 'completed');
  });
});
